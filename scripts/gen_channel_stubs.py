#!/usr/bin/env python3
"""Scan upstream Kotlin + Dart for platform channel names and emit Swift stubs.

The Android app has 200+ Kotlin plugins behind MethodChannel/EventChannel. On iOS
those channels do not exist, so any call would raise MissingPluginException. Most
Dart call sites already catch it, but the local-engine bridge does not. Registering
a Swift fallback for every discovered channel keeps the app alive and makes the
unsupported features degrade to "not installed / not available".
"""
import argparse
import os
import re

ap = argparse.ArgumentParser()
ap.add_argument("--app-dir", required=True)
ap.add_argument("--out", required=True)
args = ap.parse_args()

app_dir = os.path.abspath(args.app_dir)
upstream = os.path.dirname(app_dir)
scan_roots = [
    os.path.join(app_dir, "android"),
    os.path.join(app_dir, "lib"),
    os.path.join(upstream, "packages"),
]

files = []
for root in scan_roots:
    for base, _dirs, names in os.walk(root):
        for n in names:
            if n.endswith((".kt", ".java", ".dart")):
                files.append(os.path.join(base, n))

methods, events = set(), set()

CALL = re.compile(
    r"(MethodChannel|EventChannel|BasicMessageChannel)\s*\(([^)]{0,400}?)\)", re.S
)
STRING = re.compile(r"""['"]([^'"]+)['"]""")
LITERAL = re.compile(r"""['"]((?:dsh|io\.github|com\.)[A-Za-z0-9_./-]+)['"]""")

for path in files:
    text = open(path, encoding="utf-8", errors="replace").read()

    for kind, body in CALL.findall(text):
        names = STRING.findall(body)
        # Kotlin: MethodChannel(messenger, "dsh/runtime"); Dart: MethodChannel('dsh/runtime')
        candidates = [n for n in names if "/" in n and " " not in n]
        if not candidates:
            continue
        name = candidates[-1]
        if kind == "EventChannel" or "/events" in name or "/event" in name or name.endswith("Stream"):
            events.add(name)
        else:
            methods.add(name)

    # Constants such as: private const val CHANNEL = "dsh/runtime"
    for name in LITERAL.findall(text):
        if name.count("/") >= 1 and len(name) < 80 and " " not in name:
            if "/events" in name or "/event" in name or name.endswith("Stream"):
                events.add(name)
            else:
                methods.add(name)

methods -= events
# Well-known channels are always covered even if upstream renames them.
methods.update({"dsh/runtime", "dsh/launch", "dsh/update"})
events.update({"dsh/runtime/events"})
methods -= events

methods = sorted(methods)
events = sorted(events)


def swift_list(name, values):
    if not values:
        return f"    private static let {name}: [String] = []\n"
    body = "\n".join(f'        "{v}",' for v in values)
    return f"    private static let {name}: [String] = [\n{body}\n    ]\n"


swift = f"""// AUTO-GENERATED by scripts/gen_channel_stubs.py -- do not edit by hand.
// {len(methods)} method channels + {len(events)} event channels discovered upstream.
import Flutter
import Foundation

final class IosChannelStubs: NSObject {{
    private static let shared = IosChannelStubs()
{swift_list("methodChannels", methods)}
{swift_list("eventChannels", events)}
    private var sinks: [String: FlutterEventSink] = [:]

    static func register(with registrar: FlutterPluginRegistrar) {{
        let messenger = registrar.messenger()
        for name in methodChannels {{
            let channel = FlutterMethodChannel(name: name, binaryMessenger: messenger)
            channel.setMethodCallHandler {{ call, result in
                Self.handle(channel: name, method: call.method, result: result)
            }}
        }}
        for name in eventChannels {{
            let channel = FlutterEventChannel(name: name, binaryMessenger: messenger)
            channel.setStreamHandler(shared)
        }}
        NSLog("[dsh-ios] registered \\(methodChannels.count) method + "
              + "\\(eventChannels.count) event channel fallbacks")
    }}

    private static func handle(channel: String, method: String, result: @escaping FlutterResult) {{
        // The local Ubuntu/Node engine does not exist on iOS. Report it as
        // "not installed" instead of throwing MissingPluginException.
        if channel == "dsh/runtime" {{
            switch method {{
            case "getStatus":
                result(["phase": "notInstalled", "installed": false, "supported": false,
                        "running": false, "progress": 0, "ios": true])
                return
            case "getLogSnapshot":
                result(["entries": [String]()])
                return
            case "logs", "safePreflight", "failureLog", "moveAside":
                result([Any]())
                return
            case "storageStatus":
                result(["granted": false, "permission": false, "legacy": false])
                return
            case "start", "stop", "install", "reset", "requestStorage",
                 "openAllFilesAccess", "restoreLastKnownGood":
                result(false)
                return
            default:
                break
            }}
        }}

        let m = method.lowercased()
        if m.contains("list") || m.contains("logs") || m.contains("entries") {{
            result([Any]())
            return
        }}
        if m.hasPrefix("is") || m.hasPrefix("has") || m.hasPrefix("can")
            || m.contains("enabled") || m.contains("available")
            || m.contains("supported") || m.contains("granted")
            || m.contains("open") || m.contains("request") {{
            result(false)
            return
        }}
        // null is the safest default: invokeMethod / invokeMapMethod /
        // invokeListMethod all accept it, and most call sites use `?? fallback`.
        result(nil)
    }}
}}

extension IosChannelStubs: FlutterStreamHandler {{
    func onListen(withArguments arguments: Any?,
                  eventSink events: @escaping FlutterEventSink) -> FlutterError? {{
        // Keep the stream open without emitting. Dart-side parsers ignore
        // unknown events, so emitting a real status here is riskier than silence.
        Self.shared.sinks["default"] = events
        return nil
    }}

    func onCancel(withArguments arguments: Any?) -> FlutterError? {{
        Self.shared.sinks.removeValue(forKey: "default")
        return nil
    }}
}}
"""

os.makedirs(os.path.dirname(args.out), exist_ok=True)
open(args.out, "w", encoding="utf-8").write(swift)
print(f"[stubs] {len(files)} source files scanned")
print(f"[stubs] method channels ({len(methods)}): {', '.join(methods[:25])}"
      + (" ..." if len(methods) > 25 else ""))
print(f"[stubs] event channels  ({len(events)}): {', '.join(events)}")
print(f"[stubs] wrote {args.out}")
